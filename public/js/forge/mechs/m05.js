    const piv = new THREE.Group();
    parent.add(piv);
    const skin = solid ? PAL.mid : PAL.lite;
    const opt = solid
      ? { metalness: 0.45, side: THREE.DoubleSide }
      : { metalness: 0.2, transparent: true, opacity: 0.4, side: THREE.DoubleSide };
    const fx = solid ? 1 : this.FOLD.x, fy = solid ? 1 : this.FOLD.y;
    // ⚠ 輪廓點是**軀幹絕對座標**(x = 離體中線、y = 離地),局部原點離多邊形很遠 ⇒
    //   收攏係數一動,整片膜也跟著往原點滑走。收摺態因此先把**內緣中點**(= 膜真正掛在
    //   體側的那條線的中央)移到局部原點再收攏 ⇒ 係數與呼叫端的擺位從此互不干擾,
    //   `w.position` 指的就是「這片皮掛在體側的哪一點」。展開態錨點恆 (0,0)(逐位元同舊制)。
    const mx = (x) => (sx >= 0 ? x : -x);
