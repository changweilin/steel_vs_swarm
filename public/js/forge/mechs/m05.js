    // 收摺態改吃細摺痕參數:皮褶上的摺痕是**膜面上的紋路**,不是一副撐開的傘骨。
    // 2026-08-14 展開態實拍判退:四根膜骨各自帶著一圈反轉外殼躺在一片平板上 ⇒ 整片膜讀成
