    const a2 = P.reduce((a, p, i) => { const q = P[(i + 1) % P.length]; return a + p[0] * q[1] - q[0] * p[1]; }, 0);
    const m = prismF(piv, a2 < 0 ? P.slice().reverse() : P, 0.03, 0, 0, 0, skin, opt);  // 膜面(腕—踝之間的大片皮膜)
    m.userData.noOutline = !solid;                       // 半透明薄片:反轉外殼會糊成黑片(A16)
