    const { PAL } = c;
    const n = segs.length;
    // ⚠ **相鄰羽片的間距 MUST 小於羽寬**,否則尾翼讀起來是一副魚骨而不是一片翼面。
    //   兩個獨立的量都要顧,r2/r3 各踩一次:
    //   ㋐ **沿尾軸的覆蓋** = L·cos(splay) 要大於間距。r2 的 (L̄ 0.50, splay 1.13) 只覆蓋
    //      0.21m < 尾節 0.36m ⇒ 每一對之間露出一段光禿的尾椎;現值覆蓋 0.41m。
    //   ㋑ **每節一對還是不夠**:一根尾節 0.36~0.46m 長而羽寬只有 0.13m ⇒ 就算羽片斜著
