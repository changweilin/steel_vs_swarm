const BODY = [
  [-2.30, 0.20], [-2.00, 0.28], [-1.60, 0.42], [-1.15, 0.58], [-0.55, 0.73],
  [0.15, 0.83], [0.85, 0.90], [1.45, 0.93], [1.95, 0.86], [2.30, 0.74],
];
const rAt = (z) => {
  if (z <= BODY[0][0]) return BODY[0][1];
  for (let i = 1; i < BODY.length; i++) {
    const [z1, r1] = BODY[i];
    if (z <= z1) {
      const [z0, r0] = BODY[i - 1];
      return r0 + (r1 - r0) * (z - z0) / (z1 - z0);
    }
  }
  return BODY[BODY.length - 1][1];
};

