export function buildIndividualBody(v,{box,cyl,beam,wheel}) {
  const model=INDIVIDUAL_BODIES[v.key];
  if(!model)throw new RangeError('缺少獨立車體:'+v.key);
  const {length:L,height:H,width:W}=v;
  const palette={paint:v.fadedPaint,steel:0xa4adb1,dark:0x27343c,glass:0x345d70};
  const color=c=>typeof c==='string'?palette[c]:c;
  for(const [x,r,z,w] of model.wheels)wheel(x*L,r*H,z*W,w*W);
  for(const [name,x,y,z,l,h,w,c,rotation] of model.boxes) {
    const role=v.power==='battery'&&name==='engine'?'electric_motor'
      :v.power==='battery'&&name==='sculpted_fuel_tank'?'battery_upper_casing':name;
    box(role,x*L,y*H,z*W,l*L,h*H,w*W,color(c),rotation);
  }
  for(const [name,a,b,r,c] of model.beams)beam(name,[a[0]*L,a[1]*H,a[2]*W],[b[0]*L,b[1]*H,b[2]*W],r*W,color(c));
  for(const [name,x,y,z,r,h,c,rotation] of model.cylinders)cyl(name,x*L,y*H,z*W,r*W,h*(rotation.every(n=>n===0)?H:W),color(c),rotation);
}
