/**
 * 逐機解析成驅動端要的東西(locomotion 只認這個回傳值,MUST NOT 自己讀 POSTURE/CURVES)。
 * @param limb 逐機檔 `gait.limb`:{ fore, hind, foreRole, hindRole, reachF, lockF, bounceF }
 *             ── 兩邊各自的站姿(前後可以不同:貓科前肢趾行、象四肢皆柱狀、
 *                s03 前爪抱胸 ⇒ foreRole 'grasp' 而後肢 digitigrade)
 * 省略 ⇒ 前後皆 digitigrade(獸型的多數),`grasp`/`arthropod` 由 role 自己帶同名站姿。
 */
export function limbProfile(spec) {
  // ⚠ 預設參數只擋 undefined:鷹架交出來的是 `GA.limb || null`(沒寫 limb 的機體 = null)
  //    ⇒ MUST 顯式收 null,否則那幾台會在第一幀讀 null.foreRole 直接炸
  const limb = spec || {};
  const mk = (side, defRole) => {
    const role = limb[side === 'fore' ? 'foreRole' : 'hindRole'] || defRole;
    const pk = limb[side] || (POSTURE[role] ? role : 'digitigrade');
    const P = POSTURE[pk] || POSTURE.digitigrade;
    return {
      role, posture: pk,
      reach: P.reach.map((r) => r * (limb.reachF ?? 1)),
      lock: P.lock * (limb.lockF ?? 1),
      bounce: P.bounce * (limb.bounceF ?? 1),
    };
  };
  return { fore: mk('fore', limb.foreRole || 'fore'), hind: mk('hind', limb.hindRole || 'hind') };
}

/**
 * 驅動端的單一入口:回傳這一節該吃的**屈曲量**(已含站姿行程與支撐相鎖死)。
 * locomotion.js flexChain 只呼叫這一支。
 * @param P   limbProfile 的 fore/hind 其中一半
 * @param i   關節序
 * @param u   週期比
 * @param duty 佔空比
 * @param amp 步態振幅 0..1(速度佔頂速的比;靜止 = 0 ⇒ 回落到 rest 常屈角)
 */
export function limbFlex(P, i, u, duty, amp) {
  const raw = jointFlex(P.role, i, u, duty);
  const reach = P.reach[i < 0 ? 0 : i >= P.reach.length ? P.reach.length - 1 : i];
  // 支撐相鎖死:蹄行/柱狀/蹠行的遠端在承重時被壓向「它自己的常屈角」(= 不動的承重柱),
  // 趾行幾乎不壓 —— 鎖的是**遠端**(i ≥ 1),近端不吃(把大腿也鎖死 = 整條腿變成一根柱子)
  const lock = (u < duty && i >= 1) ? P.lock : 0;
  const rest = restOf(P.role, i);
  const v = raw * (1 - lock) + rest * lock;
  // ⚠ **回傳的是相對於常屈角的增量,不是絕對屈曲量**:逐機檔的 `base` 就是那台機體站著時
  // 量出來的骨架角(t04 的犬骨架照、s06 的馬、m08 的豹…),驅動端 MUST NOT 在上面疊一個
  // 靜態偏移 —— 疊了就是「站姿被步態曲線改掉」,而畫面上只讀成「這台機體站著的樣子不一樣了」。
  // 靜止(amp → 0)⇒ 恆回 0 ⇒ 逐位元回到 base。負值 = 比站姿更伸展(蹬離那一段,是對的)。
  const a = amp < 0 ? 0 : amp > 1 ? 1 : amp;
  return (v - rest) * a * reach * FLEX_GAIN;
}

// 正規化曲線(值域 ≈0.9)→ 弧度增量的總增益。取 1.6 讓**近端關節**的擺動相峰值
// (肘 0.81 / 膝 0.55 → 1.30 / 0.88 rad·k)落在舊制通用式的同一個量級(舊制 i=0 峰值 1.30),
// ⇒ 這一輪換的是「形狀」不是「音量」,逐機 `k` 一格不用重調。
export const FLEX_GAIN = 1.6;

/** 常屈角(站著不動時這一節的屈曲量)= 該關節支撐段的中值 —— 推導不手寫 */
export function restOf(role, i) {
  const tab = CURVES[role] || CURVES.hind;
  const c = tab[i < 0 ? 0 : i >= tab.length ? tab.length - 1 : i];
  return tableAt(c.st, 0.5);
}

/** 稽核與工具用:整條曲線取樣(N 點,自觸地起算) */
export function sampleJoint(role, i, duty, N = 100) {
  const out = [];
  for (let n = 0; n < N; n++) out.push(jointFlex(role, i, n / N, duty));
  return out;
}
