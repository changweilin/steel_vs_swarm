// ── 相位慣例(與 locomotion.js 舊制逐位元對齊)──────────────────────────
// locomotion 的 `ph` 慣例:支撐相 = cos(ph) > 0 ⇒ **觸地在 ph = −π/2、離地在 ph = +π/2**。
// 本檔一律換算成「自觸地起算的週期比」u ∈ [0,1):u = 0 觸地、u = duty 離地、u → 1 回到觸地。
// duty = 0.5 時這個換算與舊制的 sw/st 半週期切分**逐位元重合** ⇒ 佔空比是唯一的新變因。
export const cycleU = (ph) => {
  const u = (ph + Math.PI / 2) / (2 * Math.PI);
  return u - Math.floor(u);
};

// ── 佔空比(支撐相佔一個步態週期的比例)────────────────────────────────
// 量到的值:慢步 0.60~0.65(恆三足觸地的前提)、小跑 0.42~0.48、襲步 0.28~0.35、
// 昆蟲三角步態 ≈0.55(任一時刻三足在地 ⇒ 每足 > 0.5 是結構要求,不是美術取捨)、
// 軟體爬行 0.60(觸手的推進波幾乎一直貼著地)。
export const GAIT_DUTY = { walk: 0.62, trot: 0.45, tripod: 0.56, crawl: 0.60, gallop: 0.30 };
export const DUTY_MIN = 0.22, DUTY_MAX = 0.72;

/**
 * 這一幀的佔空比。`gallop` 是 locomotion 算好的襲步混成度 0..1 ——
 * 小跑換襲步時佔空比 MUST 跟著連續縮短(換步態不是只換落腳順序:騰空相是「佔空比掉到
 * 0.5 以下」的**直接結果**,不跟著縮就會出現「四腳都在地上卻在騰空」的假動作)。
 */
export function dutyOf(gaitKey, gallop = 0) {
  const base = GAIT_DUTY[gaitKey] ?? GAIT_DUTY.trot;
  const g = gallop < 0 ? 0 : gallop > 1 ? 1 : gallop;
  const d = base + (GAIT_DUTY.gallop - base) * g;
  return d < DUTY_MIN ? DUTY_MIN : d > DUTY_MAX ? DUTY_MAX : d;
}

/**
 * 髖/肩驅動(−1 = 最前伸 protraction、+1 = 最後掠 retraction;與 segLimb 的 +x = 末端後移同號)。
 * 支撐相 **線性等速**由 −1 掃到 +1(腳釘在地上、身體等速前進 ⇒ 相對角速度是定值),
 * 擺動相以升餘弦快速盪回 —— 兩段在端點值與**一階導數**都接得上(接不上的話每一步會頓一下)。
 * 舊制的 sin(ph) 只在 duty = 0.5 且「支撐相角速度容許兩端慢中間快」時才近似成立。
 *
 * 導數連續的火候:支撐段斜率 = 2/duty;擺動段 −cos 形的中點斜率 = −π/(1−duty)。
 * 兩者符號相反、量級不同是對的(擺動相本來就比支撐相快),要求的只有**端點**值連續 + 端點斜率為 0,
 * 升餘弦兩端斜率恰為 0 ⇒ 只需支撐段在端點也「軟」一下,故支撐段兩端各留 ease 帶。
 */
export const HIP_EASE = 0.15;   // 支撐相兩端的緩起緩停帶(佔支撐相的比例)

export function hipDrive(u, duty) {
  const d = duty <= 0 ? 1e-3 : duty >= 1 ? 1 - 1e-3 : duty;
  if (u < d) {
    // 角速度剖面:中段恆為定值,兩端 HIP_EASE 帶內線性收到 0 ⇒ 位置是它的積分(下式)。
    // 端點斜率為 0 才接得上擺動段(升餘弦兩端斜率也是 0)—— 接不上就是每一步頓一下。
    const s = u / d, E = HIP_EASE;
    let g;
    if (s <= E) g = s * s / (2 * E);
    else if (s < 1 - E) g = E / 2 + (s - E);
    else { const t = 1 - s; g = (1 - E) - t * t / (2 * E); }
    const f = g / (1 - E);
    return -1 + 2 * (f < 0 ? 0 : f > 1 ? 1 : f);
  }
  const w = (u - d) / (1 - d);
  return 1 - 2 * (0.5 - 0.5 * Math.cos(Math.PI * w));   // +1 → −1,兩端斜率 0
}

