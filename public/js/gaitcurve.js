/** 週期線性內插(表已排序、端點含 0 與 1;表本身是設計資料,不做防呆以外的處理) */
function tableAt(tab, x) {
  const t = x < 0 ? 0 : x > 1 ? 1 : x;
  for (let i = 1; i < tab.length; i++) {
    if (t <= tab[i][0]) {
      const a = tab[i - 1], b = tab[i];
      const span = b[0] - a[0];
      const f = span <= 0 ? 0 : (t - a[0]) / span;
      // 平滑段(smoothstep):關節角的一階導數在關鍵點上不出現折角
      const s = f * f * (3 - 2 * f);
      return a[1] + (b[1] - a[1]) * s;
    }
  }
  return tab[tab.length - 1][1];
}

/**
 * 這一節、這一刻的正規化屈曲量 0..1。
 * @param role  'fore' | 'hind' | 'arthropod' | 'grasp'
 * @param i     關節序(0 = 近端第一個樞軸;超出表長 ⇒ 沿用最遠端那條曲線並逐節加深)
 * @param u     自觸地起算的週期比 [0,1)
 * @param duty  佔空比
 */
export function jointFlex(role, i, u, duty) {
  const tab = CURVES[role] || CURVES.hind;
  const n = tab.length;
  const c = tab[i < 0 ? 0 : i >= n ? n - 1 : i];
  const d = duty <= 0 ? 1e-3 : duty >= 1 ? 1 - 1e-3 : duty;
  const v = u < d ? tableAt(c.st, u / d) : tableAt(c.sw, (u - d) / (1 - d));
  // 表外的額外遠端節(五節以上的長肢):沿用末節曲線,幅度逐節遞減(末梢是被甩的,不是被驅動的)
  return i >= n ? v * Math.pow(0.72, i - n + 1) : v;
}

