          // 這一輪把板**拉長**(不是整塊平移:平移會讓它離開肩關節浮在空中):
          // 頂點 0.50 + 掛點 0.16 + hipY 1.86 = **世界 2.52**,高過背線 0.12 m。
          const sc = prismF(l, [[-0.15, -0.30], [0.17, -0.26], [0.24, 0.10], [0.04, 0.50], [-0.22, 0.28]], 0.05, sx * 0.21, 0.16, -0.03, PAL.mid, SOFT);
