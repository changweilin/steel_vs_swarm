        // 「這裡是折點」—— 深 Z 折了兩道卻沒有可辨識的關節,整條腿仍會讀成一根彎桿。
        cylF(l, 0.10, 0.10, 0.055, 10, sx * 0.085, -0.02, 0, PAL.deep, SOFT).rotation.z = Math.PI / 2;
        if (!front)
          cablesF(l, { p0: [0, -0.06, -0.13], p1: [0, -L[1] + 0.03, -0.05], k: 2, r: 0.017, sag: 0.02, spread: 0.024 }, COAL, SOFT);
