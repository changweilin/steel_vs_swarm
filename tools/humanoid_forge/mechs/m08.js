    // 摺收角是**算過的**,兩個方向都有牙:
    //   ㋐ 太開 = 擋住豹身;㋑ 太收(累積偏航 ≥ 1.4)= 整片翼壓成背上一條看不出東西的暗脊,
    //      而且飛羽在局部指向 (sin rake, 0, −cos rake) ⇒ 摺過頭時羽尖越過中線插進**對面那片**。
    //   現值累積 0.62 + 0.30 + 0.22 = 1.14 rad:最內側的三級飛羽端點落在 x ≈ +0.12(仍在自己那半),
    //   而整片翼維持 2D 地面圖那種「後掠但攤開、比機身還寬」的板狀剪影。
    //   2026-08-14 兩處微調:㋐ 三級飛羽這一輪加長(0.46→0.52 起跳)而它掛在**第一段**上
    //     ⇒ 第一段的掠角由 0.62 收到 0.58、後兩段各補回一點(累積仍是 1.14)。
    //   ㋐′ 摺收的**內側餘裕**(不是翼弦的上限):累積偏航 1.14 rad 之下,羽片與板的局部
    //     「後方」在世界座標上指向 (−sinΣ, −cosΣ) = 斜著跨過中線 ⇒ 內側零件越長、越靠近
    //     對面那片。逐件算過的落點(世界 x,右翼 ⇒ 正值 = 仍在自己那半):最內側次級飛羽
    //     +0.074、最內側三級飛羽 +0.065、**翼板 A 的內後角 +0.12**(板的內緣因此自 0.10 退到
    //     0.22)。⚠ 2026-08-14 第二輪在這裡寫過一條「鴞的翼展÷翼弦 3.3 做不到、現值 5.5」的
