          // 改制前它掛到 y −0.58,正好蓋住膝與跗之間那個缺口 ⇒ 深 Z 折出來了卻看不見。
          const hp = prismF(l, [[-0.28, -0.26], [0.1, -0.32], [0.34, -0.10], [0.36, 0.14], [0.14, 0.3], [-0.22, 0.26]], 0.05, sx * 0.22, -0.06, -0.06, PAL.mid, SOFT);
