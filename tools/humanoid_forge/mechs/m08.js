    // 一片飛羽:finF 沿 +y、面法線是局部 z ⇒ 先 Rz 掃掠、再 Rx 轉平(three 的尤拉序 'XYZ'
    // 展開成 R = Rx·Ry·Rz ⇒ **Rz 先作用**)。合成後羽面水平、羽尖指向 (sin(sx·rake), 0, −cos(rake)),
    // 即「往後、往翼尖外側耙開」;rake 越大越貼近翼展軸(外側初級飛羽的樣子)。
    const plume = (p, spec, px, py, pz, rake, col) => {
      const f = finF(p, spec, px, py, pz, col, SOFT);
      f.rotation.z = -sx * rake;
      f.rotation.x = -Math.PI / 2;
      return f;
    };
    // 一根前緣鋸齒:Rx = +π/2 ⇒ 羽尖朝 +z(前緣朝前)
    const serr = (p, px, pz) => {
      const s = finF(p, { len: 0.15, w0: 0.12, w1: 0.025, t: 0.022 }, px, 0.012, pz, PAL.lite, SOFT);
      s.rotation.z = sx * 0.12;
      s.rotation.x = Math.PI / 2;
    };
    // 一片翼板:pts = [翼展向, 弦向朝後] 的平面外形(右翼);厚度 0.075 由擠出深度給。
    // Rx(−π/2) 把 polygon +y 送到世界 −z(朝後)、把擠出軸送到 +y(厚度);
    // 左翼 MUST 鏡射 x **並** reverse 點序(見上方紀律 ⓓ)。
    const panel = (p, pts, py, col) => {
      const q = sx > 0 ? pts : pts.map(([px, pz]) => [-px, pz]).reverse();
      const b = prismF(p, q, 0.075, 0, py, 0, col, SOFT);
      b.rotation.x = -Math.PI / 2;
      return b;
    };

    // ── ① 肱骨段 ────────────────────────────────────────────────
    const sock = latheF(w, [[0.05, -0.09], [0.13, -0.07], [0.155, 0], [0.12, 0.07], [0.05, 0.10]], 10, 0, 0, 0, PAL.deep, SOFT);
    sock.rotation.z = Math.PI / 2;                    // 肩球窩(骨幹軸 = ±x)
    const hum = tboxF(w, { w0: 0.14, d0: 0.20, w1: 0.11, d1: 0.15, h: HUM }, sx * HUM * 0.5, 0, 0.01, PAL.mid, SOFT);
    hum.rotation.z = -sx * Math.PI / 2;               // 轉 −sx·π/2 才把 +y 送到 +sx·x(geo.js finF 紀律 ③)
    // 翼板 A(翼根板;2D 定案圖上那塊帶迷彩的硬板就在這一段)+ 鉚上去的裝甲貼片。
